def validate(d):
    validate_quest_polish(d)
    validate_outfits(d['actors'])
    ids = d['ids']
    assert d['chapter'] == 'C02' and len(d['quests']) == 23
    for prefix in ('QUEST_', 'GO_', 'ITEM_'):
        values = [v for k, v in ids.items() if k.startswith(prefix)]
        assert len(values) == len(set(values)), prefix
    creatures = [v for k, v in ids.items() if k.startswith(('NPC_', 'CREDIT_'))]
    assert len(creatures) == len(set(creatures))
    for p in d['points'].values():
        assert len(p) == 4 and all(math.isfinite(v) for v in p)
    for q in d['quests']:
        assert q['id'] == ids[q['key']] and q['description'] and q['completion']
        assert len(q['credits']) <= 4 and len(q['required_items']) <= 6
        assert len(q['reward_choices']) <= 6
        assert q['previous'] == q['prerequisites'][0]
    assert d['quests'][-1]['reward_choices'] and not d['quests'][-1].get('next_quest')
    # The core's negative exclusive groups enforce ALL joins in both visibility and acceptance.
    by_key = {q['key']: q for q in d['quests']}
    for q in d['quests']:
        if len(q['prerequisites']) > 1:
            groups = {by_key[k]['exclusive_group'] for k in q['prerequisites']}
            assert len(groups) == 1 and next(iter(groups)) < 0
            assert {v['key'] for v in d['quests'] if v.get('exclusive_group') in groups} == set(q['prerequisites'])


def header(d):
    lines = ['// Generated by tools/generate_broken_seal_chapter2.py. Do not edit.',
             '#ifndef MOD_CUSTOMNPCS_BROKEN_SEAL_CHAPTER2_DATA_H',
             '#define MOD_CUSTOMNPCS_BROKEN_SEAL_CHAPTER2_DATA_H', '',
             '#include <array>', '#include <cstdint>', '', 'namespace BrokenSeal::Chapter2', '{',
             'enum Id : std::uint32_t', '{']
    lines += [f'    {k} = {v},' for k, v in d['ids'].items()]
    lines += ['};', '', f'inline constexpr std::uint32_t FireDisplay = {d["native_assets"]["fire_form"]["display"]};', '', 'struct Point', '{', '    float x;', '    float y;', '    float z;',
              '    float orientation;', '};', '', 'namespace Locations', '{']
    for key, p in d['points'].items():
        lines += [f'inline constexpr Point {key} = {{' + ', '.join(f'{v:.4f}f' for v in p) + '};']
    lines += ['}', '']
    for name, keys in d['routes'].items():
        lines += [f'inline constexpr std::array<Point, {len(keys)}> {name} =',
                  '{', '    ' + ', '.join('Locations::' + k for k in keys), '};', '']
    lines += ['struct QuestSupply', '{', '    std::uint32_t quest;',
              '    std::array<std::uint32_t, 2> items;', '};', '',
              'inline constexpr std::array<QuestSupply, 9> Supplies =', '{{']
    for q in d['quests']:
        if q['recovery_items']:
            keys = q['recovery_items'] + ['0'] * (2 - len(q['recovery_items']))
            lines += ['    {' + q['key'] + ', {' + ', '.join(keys) + '}},']
    lines += ['}};', '', 'inline constexpr std::array<std::uint32_t, 23> Quests =', '{',
              '    ' + ', '.join(q['key'] for q in d['quests']), '};',
              'inline constexpr std::array<std::uint32_t, 22> PersonalEntries =', '{',
              '    ' + ', '.join(a['key'] for a in d['actors'] if not a.get('point') and not a.get('points')), '};',
              '}', '', '#endif', '']
    # Infer lengths rather than leave silently padded entries in a cleanup inventory.
    lines = [l.replace('array<std::uint32_t, 22> PersonalEntries',
                       f'array<std::uint32_t, {sum(not a.get("point") and not a.get("points") for a in d["actors"])}> PersonalEntries') for l in lines]
    return '\n'.join(lines)


