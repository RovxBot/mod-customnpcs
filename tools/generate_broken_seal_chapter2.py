def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args();d=json.loads(MANIFEST.read_text());validate(d)
    content=sql(d)
    for path,value in [(BASE,content),(UPDATE,content),(HEADER,header(d))]:
        if args.check:
            assert path.is_file() and path.read_text()==value, f'Stale generated file: {path}'
        else:
            path.parent.mkdir(parents=True,exist_ok=True);path.write_text(value)
    print('Chapter 2: validated 23 quests and generated matching SQL and runtime inventory.')


if __name__=='__main__':
    main()
